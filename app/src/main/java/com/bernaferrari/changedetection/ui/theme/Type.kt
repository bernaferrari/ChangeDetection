/**
 * Typography semantic tokens for common use cases
 * Simplifies code by using meaningful names instead of style names
 */
object TypographyTokens {
    // Page titles and major section headers
    val pageTitle get() = Typography.displaySmall

    // Section headers within pages
    val sectionHeader get() = Typography.headlineSmall

    // Card/item titles
    val cardTitle get() = Typography.titleMedium

    // Primary body content
    val bodyText get() = Typography.bodyMedium

    // Secondary/supplementary text
    val secondaryText get() = Typography.bodySmall

    // Button and interactive text
    val buttonText get() = Typography.labelLarge

    // Small captions and hints
    val captionText get() = Typography.labelSmall

    // Code/monospace content
    val codeText = TextStyle(
        fontFamily = FontFamily.Monospace,
        fontWeight = FontWeight.Normal,
        fontSize = 12.sp,
        lineHeight = 16.sp,
        letterSpacing = 0.sp
    )
}
